export function fallbackTranslate(key, params) {
  const dict = DICT.zh
  const template = dict[key] ?? DICT.en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match))
}
